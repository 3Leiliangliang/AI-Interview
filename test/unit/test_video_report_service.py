class TestGenerateReport:
    """Test full report generation."""

    async def test_generate_report_with_events(self, service, mock_event_service):
        """Should generate a complete report when events are available."""
        mock_event_service.aggregate_events.return_value = _make_aggregated()

        # Mock LLM to return valid JSON
        mock_model = AsyncMock()
        mock_response = MagicMock()
        mock_response.content = json.dumps({
            "overall_impression": "面试者整体表现稳定。",
            "dimension_analysis": {
                "emotion": "情绪控制良好。",
                "posture": "姿态基本端正。",
                "attention": "注意力较为集中。",
            },
            "recommendations": ["保持良好的情绪管理", "注意坐姿"],
            "strengths": ["情绪稳定", "姿态端正"],
        })
        mock_model.call = AsyncMock(return_value=mock_response)

        with patch("src.services.video_report_service.select_model", return_value=mock_model):
            report = await service.generate_report("sess-123")

        assert report["session_id"] == "sess-123"
        assert "scores" in report
        assert "overall_impression" in report
        assert "recommendations" in report
        assert "strengths" in report

    async def test_generate_report_no_events(self, service, mock_event_service):
        """Should return empty report when no events available."""
        mock_event_service.aggregate_events.return_value = {"has_data": False}

        report = await service.generate_report("sess-empty")

        assert report["session_id"] == "sess-empty"
        assert report["has_data"] is False
        assert report["scores"] == {}
        assert report["recommendations"] == []

    async def test_generate_report_llm_fallback(self, service, mock_event_service):
        """Should fallback to rule-based scoring when LLM fails."""
        mock_event_service.aggregate_events.return_value = _make_aggregated()

        with patch("src.services.video_report_service.select_model", side_effect=Exception("LLM unavailable")):
            report = await service.generate_report("sess-llm-fail")

        assert report["session_id"] == "sess-llm-fail"
        assert "scores" in report
        assert "emotion_stability" in report["scores"]
        # Fallback should still have recommendations generated by rules
        assert isinstance(report["recommendations"], list)

    async def test_generate_report_llm_returns_invalid_json(self, service, mock_event_service):
        """Should fallback when LLM returns non-JSON response."""
        mock_event_service.aggregate_events.return_value = _make_aggregated()

        mock_model = AsyncMock()
        mock_response = MagicMock()
        mock_response.content = "This is not valid JSON"
        mock_model.call = AsyncMock(return_value=mock_response)

        with patch("src.services.video_report_service.select_model", return_value=mock_model):
            report = await service.generate_report("sess-bad-json")

        assert report["session_id"] == "sess-bad-json"
