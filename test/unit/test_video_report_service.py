class TestFormatReportPrompt:
    """Test LLM prompt formatting."""

    def test_prompt_contains_scores(self, service):
        """Prompt should include all dimension scores."""
        scores = {"emotion_stability": 85, "posture": 90, "attention": 75, "overall": 82}
        aggregated = _make_aggregated()

        prompt = service._format_report_prompt(scores, aggregated)

        assert "85" in prompt
        assert "90" in prompt
        assert "75" in prompt
        assert "82" in prompt

    def test_prompt_requests_json_output(self, service):
        """Prompt should request JSON output format."""
        scores = {"emotion_stability": 80, "posture": 80, "attention": 80, "overall": 80}
        aggregated = _make_aggregated()

        prompt = service._format_report_prompt(scores, aggregated)

        assert "JSON" in prompt.upper() or "json" in prompt

    def test_prompt_contains_emotion_details(self, service):
        """Prompt should include dominant emotion and emotion distribution."""
        scores = {"emotion_stability": 80, "posture": 80, "attention": 80, "overall": 80}
        aggregated = _make_aggregated(
            dominant_emotion="happy",
            emotion_scores={"happy": 0.7, "neutral": 0.3},
        )

        prompt = service._format_report_prompt(scores, aggregated)

        assert "happy" in prompt

    def test_prompt_contains_alerts(self, service):
        """Prompt should include alert information."""
        scores = {"emotion_stability": 80, "posture": 80, "attention": 80, "overall": 80}
        aggregated = _make_aggregated(
            recent_alerts=[{"type": "gaze", "message": "Looking away"}],
        )

        prompt = service._format_report_prompt(scores, aggregated)

        assert "Looking away" in prompt


