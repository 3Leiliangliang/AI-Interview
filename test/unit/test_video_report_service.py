class TestComputeScores:
    """Test dimension score computation."""

    def test_compute_scores_all_dimensions(self, service):
        """Should compute all four dimension scores."""
        aggregated = _make_aggregated(
            emotion_scores={"neutral": 0.6, "happy": 0.3, "sad": 0.1},
            avg_posture_score=85.0,
            avg_attention_score=78.0,
        )
        scores = service._compute_scores(aggregated)

        assert "emotion_stability" in scores
        assert "posture" in scores
        assert "attention" in scores
        assert "overall" in scores

    def test_compute_scores_emotion_stability(self, service):
        """Emotion stability should be higher when one emotion dominates."""
        # Neutral dominates -> high stability
        stable = _make_aggregated(emotion_scores={"neutral": 0.9, "happy": 0.05, "sad": 0.05})
        scores_stable = service._compute_scores(stable)

        # Mixed emotions -> lower stability
        mixed = _make_aggregated(emotion_scores={"happy": 0.33, "sad": 0.33, "angry": 0.34})
        scores_mixed = service._compute_scores(mixed)

        assert scores_stable["emotion_stability"] > scores_mixed["emotion_stability"]

    def test_compute_scores_posture_uses_average(self, service):
        """Posture score should directly use avg_posture_score."""
        aggregated = _make_aggregated(avg_posture_score=92.0)
        scores = service._compute_scores(aggregated)
        assert scores["posture"] == 92.0

    def test_compute_scores_attention_uses_average(self, service):
        """Attention score should directly use avg_attention_score."""
        aggregated = _make_aggregated(avg_attention_score=65.0)
        scores = service._compute_scores(aggregated)
        assert scores["attention"] == 65.0

    def test_compute_scores_overall_weighted(self, service):
        """Overall score should be 0.3*emotion + 0.3*posture + 0.4*attention."""
        aggregated = _make_aggregated(
            emotion_scores={"neutral": 0.9, "happy": 0.1},
            avg_posture_score=80.0,
            avg_attention_score=70.0,
        )
        scores = service._compute_scores(aggregated)

        expected = 0.3 * scores["emotion_stability"] + 0.3 * 80.0 + 0.4 * 70.0
        assert abs(scores["overall"] - round(expected, 1)) < 0.5

    def test_compute_scores_missing_posture(self, service):
        """Missing posture score should default to a reasonable value."""
        aggregated = _make_aggregated(avg_posture_score=None)
        scores = service._compute_scores(aggregated)
        # Should still have a valid score (e.g. 70 as default)
        assert scores["posture"] == 70.0

    def test_compute_scores_missing_attention(self, service):
        """Missing attention score should default to a reasonable value."""
        aggregated = _make_aggregated(avg_attention_score=None)
        scores = service._compute_scores(aggregated)
        assert scores["attention"] == 70.0

    def test_compute_scores_empty_emotions(self, service):
        """Empty emotion scores should default to moderate stability."""
        aggregated = _make_aggregated(emotion_scores={})
        scores = service._compute_scores(aggregated)
        assert scores["emotion_stability"] == 70.0


