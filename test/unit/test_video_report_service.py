class TestGenerateRecommendations:
    """Test fallback recommendation generation."""

    def test_recommendations_low_attention(self, service):
        """Low attention score should generate attention-related recommendation."""
        scores = {"emotion_stability": 80, "posture": 80, "attention": 40, "overall": 60}
        aggregated = _make_aggregated()

        recs = service._generate_rule_based_recommendations(scores, aggregated)

        assert any("注意力" in r for r in recs)

    def test_recommendations_low_posture(self, service):
        """Low posture score should generate posture-related recommendation."""
        scores = {"emotion_stability": 80, "posture": 50, "attention": 80, "overall": 70}
        aggregated = _make_aggregated()

        recs = service._generate_rule_based_recommendations(scores, aggregated)

        assert any("姿态" in r or "坐姿" in r for r in recs)

    def test_recommendations_low_emotion_stability(self, service):
        """Low emotion stability should generate emotion-related recommendation."""
        scores = {"emotion_stability": 40, "posture": 80, "attention": 80, "overall": 68}
        aggregated = _make_aggregated()

        recs = service._generate_rule_based_recommendations(scores, aggregated)

        assert any("情绪" in r for r in recs)

    def test_recommendations_high_scores(self, service):
        """High scores should generate positive recommendations."""
        scores = {"emotion_stability": 95, "posture": 95, "attention": 95, "overall": 95}
        aggregated = _make_aggregated()

        recs = service._generate_rule_based_recommendations(scores, aggregated)

        assert len(recs) > 0
        # Should have positive suggestions
        assert any("保持" in r or "继续" in r for r in recs)

    def test_recommendations_returns_list(self, service):
        """Should always return a list."""
        scores = {"emotion_stability": 80, "posture": 80, "attention": 80, "overall": 80}
        aggregated = _make_aggregated()

        recs = service._generate_rule_based_recommendations(scores, aggregated)

        assert isinstance(recs, list)
        assert len(recs) >= 1
